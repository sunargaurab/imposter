export function getCategoryById(id: string): Category {
  const found = CATEGORIES.find(c => c.id === id);
  return found || CATEGORIES[0];
}

export function getRandomCategory(categoryIds?: string[]): Category {
  if (!categoryIds || categoryIds.length === 0) return CATEGORIES[0];
  const selected = CATEGORIES.filter(c => categoryIds.includes(c.id));
  if (selected.length === 0) return CATEGORIES[0];
  const idx = Math.floor(Math.random() * selected.length);
  return selected[idx];
}

export function getRandomWord(category: Category, usedWords: string[] = []): string {
  const available = category.words.filter(w => !usedWords.includes(w));
  const pool = available.length > 0 ? available : category.words;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
